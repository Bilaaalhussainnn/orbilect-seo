"use client";

import { useState, type PointerEvent } from "react";
import { ArrowRight, Braces, FileText, Image, Link2, PanelTop, Search } from "lucide-react";
import styles from "./on-page-subservices.module.css";

const services = [
  { ...({"name":"Backlink audit","location":"Backlink audit","example":"Unclear which sites refer traffic","copy":"Review referring pages and how they relate to your business.","deliverable":"Prioritized list of useful links and issues."}), icon: Search },
  { ...({"name":"Citation cleanup","location":"Citation cleanup","example":"Old contact details on directories","copy":"Correct priority listings using the current business details.","deliverable":"Consistent phone, address, and destination URLs."}), icon: PanelTop },
  { ...({"name":"Link reclamation","location":"Link reclamation","example":"A publication links to a retired URL","copy":"Find the correct replacement and request a link update where appropriate.","deliverable":"Verified destination or a working redirect."}), icon: FileText },
  { ...({"name":"Digital PR outreach","location":"Digital PR outreach","example":"Useful expertise goes uncited","copy":"Turn original insight or a project into a pitch for relevant editors.","deliverable":"Outreach log and earned placements where secured."}), icon: Link2 },
  { ...({"name":"Review and reputation support","location":"Review and reputation support","example":"The same complaint keeps appearing","copy":"Identify the operational issue and help the team respond and resolve it.","deliverable":"A response process and a list of recurring fixes."}), icon: Image },
  { ...({"name":"Referral reporting","location":"Referral reporting","example":"Your business is missing from the places customers check","copy":"Review enquiries from directories, trade publications, and other referring sites.","deliverable":"A follow-up check and next-step recommendations."}), icon: Braces }
];

export function OnPageSubservices() {
  const [active, setActive] = useState(0);
  const service = services[active];
  const Icon = service.icon;

  function tilt(event: PointerEvent<HTMLDivElement>) {
    if (event.pointerType !== "mouse") return;
    const area = event.currentTarget;
    const rect = area.getBoundingClientRect();
    area.style.setProperty("--tilt-x", ((0.5 - (event.clientY - rect.top) / rect.height) * 8) + "deg");
    area.style.setProperty("--tilt-y", (((event.clientX - rect.left) / rect.width - 0.5) * 10) + "deg");
  }

  function resetTilt(event: PointerEvent<HTMLDivElement>) {
    event.currentTarget.style.removeProperty("--tilt-x");
    event.currentTarget.style.removeProperty("--tilt-y");
  }

  return (
    <section id="on-page-subservices" className={styles.section} aria-labelledby="on-page-subservices-title">
      <div className={styles.wrap}>
        <header className={styles.header}>
          <p className={styles.eyebrow} data-site-eyebrow="">Off-page SEO sub-services</p>
          <h2 id="on-page-subservices-title">{"What we improve "}<span>{"for your business"}</span></h2>
          <p>{"Choose a service to see what we check, what we change, and what you’ll receive."}</p>
        </header>

        <div className={styles.layout}>
          <div className={styles.controls} role="group" aria-label="Choose an Off-page SEO sub-service">
            {services.map(({ name, icon: ControlIcon }, index) => (
              <button key={name} type="button" aria-pressed={index === active}
                aria-controls="on-page-subservice-preview" onClick={() => setActive(index)}>
                <ControlIcon size={19} aria-hidden="true" />
                <span>{name}</span>
                <ArrowRight className={styles.arrow} size={17} aria-hidden="true" />
              </button>
            ))}
          </div>

          <div id="on-page-subservice-preview" aria-live="polite" aria-atomic="true">
            <div className={styles.stage} onPointerMove={tilt} onPointerLeave={resetTilt}>
              <div className={styles.device}>
                <div className={styles.chrome}>
                  <span className={styles.dots} aria-hidden="true"><i /><i /><i /></span>
                  <span>example.com/off-page-seo</span>
                </div>
                <div className={styles.screen} key={service.name}>
                  <div className={styles.target}>
                    <Icon size={21} aria-hidden="true" />
                    <div><span>{service.location}</span><strong>{service.example}</strong></div>
                  </div>
                  <div className={styles.lines} aria-hidden="true"><i /><i /><i /></div>
                </div>
              </div>
            </div>
            <div className={styles.explanation} key={service.name}>
              <h3>{service.name}</h3>
              <p>{service.copy}</p>
              <p className={styles.deliverable}><strong>What you get</strong>{service.deliverable}</p>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
